ok('size without UK/US rejected', (await err(`insert into product_variants (product_id, sku, size_value, quantity) values ($1,'RT-TST-44','44',1)`, [pid]))?.code === '22023')
ok('size with EU/UK/US accepted', !(await err(`insert into product_variants (product_id, sku, size_value, uk_size, us_size, quantity) values ($1,'RT-TST-44','44','9.5','10.5',1)`, [pid])))
ok('invalid UK size rejected', !!(await err(`insert into product_variants (product_id, sku, size_value, uk_size, us_size, quantity) values ($1,'RT-TST-45','45','abc','11',1)`, [pid])))
ok('cm size optional (none given)', (await q(`select cm_size from product_variants where sku = 'RT-TST-44'`))[0]?.cm_size === null)
