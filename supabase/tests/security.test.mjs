ok('cm size outside 10-40 rejected', !!(await err(`update product_variants set cm_size = '55' where sku = 'RT-TST-44'`)))
ok('non-numeric cm size rejected', !!(await err(`update product_variants set cm_size = 'big' where sku = 'RT-TST-44'`)))
await q(`delete from product_variants where sku = 'RT-TST-44'`)
await as(alice)
ok('customer cannot read purchase prices', (await q(`select * from product_costs`)).length === 0)
ok('customer cannot read dashboard', (await err(`select dashboard_summary()`))?.code === '42501')
ok('customer cannot list customers', (await err(`select * from customer_summaries()`))?.code === '42501')
await as('anon')
ok('anon cannot touch purchase prices', !!(await err(`select * from product_costs`)))

await as(shop)
await q(`select update_order_status($1,'delivered')`, [o2.id])
const o2items = await q(`select id, quantity from order_items where order_id=$1 order by quantity`, [o2.id])
await as(alice)
const ret = (await q(`select * from request_return($1, 1, 'wrong_size', 'Too small')`, [o2items[0].id]))[0]
ok('customer requests return on delivered order', ret?.return_number?.startsWith('RET-'), ret?.return_number)
ok('cannot return more than bought', (await err(`select request_return($1, 1, 'other')`, [o2items[0].id]))?.code === '22023')
ok('customer cannot approve own return', (await err(`select update_return($1,'approved')`, [ret.id]))?.code === '42501')
await as(bob)
ok('other customer cannot return the item', (await err(`select request_return($1, 1, 'other')`, [o2items[1].id]))?.code === 'P0002')
ok('other customer cannot see the return', (await q(`select id from returns`)).length === 0)
