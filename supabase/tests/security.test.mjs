// npm run test:db — runs RajaThrifs migrations on PGlite with Supabase-like stubs, then attacks them per role.
import { createTestDb } from './harness.mjs'

const { db, ok, as, q, err, mkUser, done } = await createTestDb()

// ── Users & roles ───────────────────────────────────────────────────────────
console.log('\n# Profiles & roles')
await as('postgres')
const admin = await mkUser('admin@rt.pk', { full_name: 'Admin' })
const shop = await mkUser('shop@rt.pk', { full_name: 'Shop Keeper' })
const alice = await mkUser('alice@rt.pk', { full_name: 'Alice', phone: '+92 300 1234567' })
const bob = await mkUser('bob@rt.pk', { full_name: 'Bob', phone: 'not-a-phone' })
ok('profile auto-created with metadata', (await q(`select full_name, phone, role from profiles where id=$1`, [alice]))[0]?.phone === '+92 300 1234567')
ok('malformed phone does not block signup', (await q(`select phone from profiles where id=$1`, [bob]))[0]?.phone === null)
await q(`update profiles set role='admin' where id=$1`, [admin])

await as(alice)
ok('customer cannot escalate own role', !!(await err(`update profiles set role='admin' where id=$1`, [alice])))
ok('customer can edit own name', (await err(`update profiles set full_name='Alice K' where id=$1`, [alice])) === null)
await db.exec(`update profiles set full_name='Hacked' where id='${bob}'`)
await as('postgres')
ok('customer cannot edit another profile', (await q(`select full_name from profiles where id=$1`, [bob]))[0].full_name === 'Bob')
await as(alice)
ok('customer sees only own profile', (await q(`select id from profiles`)).length === 1)
ok('customer cannot call set_user_role', (await err(`select set_user_role($1,'admin')`, [alice]))?.code === '42501')

await as(admin)
await q(`select set_user_role($1,'shopkeeper')`, [shop])
ok('admin promotes shopkeeper', (await q(`select role from profiles where id=$1`, [shop]))[0].role === 'shopkeeper')
ok('admin cannot demote self', (await err(`select set_user_role($1,'customer')`, [admin]))?.code === '42501')
ok('admin reads all profiles', (await q(`select id from profiles`)).length === 4)

// ── Catalog ─────────────────────────────────────────────────────────────────
console.log('\n# Catalog & product CRUD')
await as(shop)
const nike = (await q(`select id from brands where slug='nike'`))[0].id
const sneakers = (await q(`select id from categories where slug='sneakers'`))[0].id
const product = (pid, slug, status, variants) => ({
  p: JSON.stringify({ id: pid ?? '', slug, name: 'Jordan 1 Low', brand_id: nike, category_id: sneakers, collection: 'PREMIUM',
    condition: 'like_new', price: '24500.00', compare_at_price: '32000', status, defects: [{ area: 'Heel', severity: 'minor', description: 'Scuff' }] }),
  v: JSON.stringify(variants),
})
let x = product(null, 'jordan-1-low', 'active', [{ sku: 'rt-prm-001-42', size_value: '42', uk_size: '8', us_size: '9', quantity: 1 }, { sku: 'RT-PRM-001-43', size_value: '43', uk_size: '9', us_size: '10', quantity: 2 }])
const pid = (await q(`select save_product($1::jsonb, $2::jsonb) as id`, [x.p, x.v]))[0].id
ok('shopkeeper creates product with variants', !!pid)
const vars = await q(`select id, sku, size_value, quantity from product_variants where product_id=$1 order by size_value`, [pid])
ok('SKU normalised to upper case', vars[0].sku === 'RT-PRM-001-42')
ok('initial stock logged as intake', (await q(`select count(*)::int c from inventory_movements where reason='intake'`))[0].c === 2)
x = product(null, 'draft-pair', 'draft', [{ sku: 'RT-DRF-001-40', size_value: '40', uk_size: '6.5', us_size: '7', quantity: 1 }])
await q(`select save_product($1::jsonb, $2::jsonb)`, [x.p, x.v])
await q(`insert into product_images (product_id, storage_path, view) values ($1, $2, 'side')`, [pid, `products/${pid}/a.jpg`])
ok('one image per standard view enforced', !!(await err(`insert into product_images (product_id, storage_path, view) values ($1, $2, 'side')`, [pid, `products/${pid}/b.jpg`])))
ok('bad storage path rejected', !!(await err(`insert into product_images (product_id, storage_path) values ($1, 'evil/../x.jpg')`, [pid])))
// edit: change qty on 43 → ledger adjustment
x = product(pid, 'jordan-1-low', 'active', [{ id: vars[0].id, sku: 'RT-PRM-001-42', size_value: '42', uk_size: '8', us_size: '9', quantity: 1 }, { id: vars[1].id, sku: 'RT-PRM-001-43', size_value: '43', uk_size: '9', us_size: '10', quantity: 3 }])
await q(`select save_product($1::jsonb, $2::jsonb)`, [x.p, x.v])
ok('editor qty change logged as adjustment', (await q(`select delta from inventory_movements where reason='adjustment'`))[0]?.delta === 1)
ok('shopkeeper cannot delete product', (await q(`delete from products where id=$1 returning id`, [pid])).length === 0)
ok('price stored as numeric PKR', (await q(`select price::text from products where id=$1`, [pid]))[0].price === '24500.00')

await as('anon')
ok('anon sees active, not draft', (await q(`select slug from products`)).map((r) => r.slug).join() === 'jordan-1-low')
ok('anon sees draft variants? no', (await q(`select sku from product_variants`)).length === 2)
ok('anon cannot read ledger', (await q(`select id from inventory_movements`)).length === 0)
ok('anon cannot insert product', !!(await err(`insert into products (slug,name,brand_id,collection,condition,price) values ('x','xx',$1,'PREMIUM','good',1)`, [nike])))
ok('anon cannot call place_order', !!(await err(`select place_order('[]','{}','{}','cod')`)))
await as(alice)
ok('customer cannot update price', (await q(`update products set price=1 where id=$1 returning id`, [pid])).length === 0)
ok('customer cannot set stock', (await q(`update product_variants set quantity=99 returning id`)).length === 0)
ok('customer cannot adjust_stock', (await err(`select adjust_stock($1, 5, 'intake')`, [vars[0].id]))?.code === '42501')
ok('customer cannot upload image', !!(await err(`insert into storage.objects (bucket_id, name) values ('product-images','x.jpg')`)))
await as(shop)
ok('staff can upload image', (await err(`insert into storage.objects (bucket_id, name) values ('product-images','products/x/y.jpg')`)) === null)

// ── Checkout ────────────────────────────────────────────────────────────────
console.log('\n# Checkout & stock')
const contact = JSON.stringify({ name: 'Alice K', phone: '+92 300 1234567', email: 'alice@rt.pk' })
const addr = JSON.stringify({ line1: 'House 1, Street 2', city: 'Lahore', province: 'Punjab' })
const items = (arr) => JSON.stringify(arr.map(([v, qty]) => ({ variant_id: v, quantity: qty })))
await as(alice)
const o1 = (await q(`select * from place_order($1::jsonb,$2::jsonb,$3::jsonb,'cod','Ring the bell')`, [items([[vars[0].id, 1], [vars[1].id, 2]]), contact, addr]))[0]
ok('order placed', o1?.order_number?.startsWith('RT-'), o1?.order_number)
ok('server-side subtotal (24500×3)', o1.subtotal === '73500.00' || Number(o1.subtotal) === 73500, String(o1.subtotal))
ok('total generated', Number(o1.total) === 73500)
ok('order items snapshot', (await q(`select count(*)::int c from order_items where order_id=$1`, [o1.id]))[0].c === 2)
ok('payment row created', (await q(`select amount from payments where order_id=$1`, [o1.id])).length === 1)
await as(shop)
ok('stock decremented', (await q(`select quantity from product_variants where product_id=$1 order by size_value`, [pid])).map((r) => r.quantity).join() === '0,1')
ok('sale movements tied to order', (await q(`select count(*)::int c from inventory_movements where reason='sale' and order_id=$1`, [o1.id]))[0].c === 2)

await as(bob)
const oversell = await err(`select place_order($1::jsonb,$2::jsonb,$3::jsonb,'cod')`, [items([[vars[0].id, 1]]), contact, addr])
ok('second buyer cannot get last pair', oversell?.hint === 'OUT_OF_STOCK', oversell?.message)
ok('failed checkout rolled back (no order)', (await q(`select id from orders`)).length === 0)
ok('quantity 0 rejected', (await err(`select place_order($1::jsonb,$2::jsonb,$3::jsonb,'cod')`, [items([[vars[1].id, 0]]), contact, addr]))?.code === '22023')
ok('card payment rejected', (await err(`select place_order($1::jsonb,$2::jsonb,$3::jsonb,'card')`, [items([[vars[1].id, 1]]), contact, addr]))?.code === '22023')
ok('unknown variant rejected', (await err(`select place_order($1::jsonb,$2::jsonb,$3::jsonb,'cod')`, [items([['00000000-0000-0000-0000-000000000000', 1]]), contact, addr]))?.hint === 'OUT_OF_STOCK')
ok('bob cannot see alice order', (await q(`select id from orders`)).length === 0)
ok('bob cannot see alice items', (await q(`select id from order_items`)).length === 0)
ok('bob cannot cancel alice order', (await err(`select cancel_order($1)`, [o1.id]))?.code === 'P0002')
ok('customer cannot insert order directly', !!(await err(`insert into orders (user_id,payment_method,contact_name,contact_phone,shipping_address_line1,shipping_city) values ($1,'cod','Bob','03001234567','abc','Lahore')`, [bob])))

await as(alice)
ok('customer cannot set tracking', (await q(`update orders set tracking_number='x' returning id`)).length === 0)
await q(`select cancel_order($1)`, [o1.id])
await as(shop)
ok('cancel restocks', (await q(`select quantity from product_variants where product_id=$1 order by size_value`, [pid])).map((r) => r.quantity).join() === '1,3')
ok('product back to active', (await q(`select status from products where id=$1`, [pid]))[0].status === 'active')

await as(alice)
const o2 = (await q(`select * from place_order($1::jsonb,$2::jsonb,$3::jsonb,'bank_transfer')`, [items([[vars[0].id, 1], [vars[1].id, 3]]), contact, addr]))[0]
await as(shop)
ok('product auto sold_out', (await q(`select status from products where id=$1`, [pid]))[0].status === 'sold_out')
await as('anon')
ok('sold out still visible to public', (await q(`select id from products where id=$1`, [pid])).length === 1)
await as(shop)
ok('invalid transition blocked', (await err(`select update_order_status($1,'delivered')`, [o2.id]))?.code === '22023')
ok('shopkeeper cannot confirm an unverified bank transfer', (await err(`select update_order_status($1,'confirmed')`, [o2.id]))?.code === '42501')
ok('shopkeeper cannot mark a bank transfer paid', (await err(`select record_payment($1,'paid')`, [o2.id]))?.code === '42501')
ok('shopkeeper cannot call approve_order', (await err(`select approve_order($1)`, [o2.id]))?.code === '42501')
await as(admin)
ok('admin cannot confirm before verifying payment', (await err(`select update_order_status($1,'confirmed')`, [o2.id]))?.code === '22023')
const approved = (await q(`select * from approve_order($1, 'BANK-REF-1')`, [o2.id]))[0]
ok('admin approve = paid + confirmed', approved.status === 'confirmed' && approved.payment_status === 'paid')
ok('approve twice rejected', (await err(`select approve_order($1)`, [o2.id]))?.code === '22023')
await as(shop)
await q(`select update_order_status($1,'shipped')`, [o2.id])
await q(`update orders set tracking_number='TCS-123' where id=$1`, [o2.id])
ok('staff sets tracking', (await q(`select tracking_number from orders where id=$1`, [o2.id]))[0].tracking_number === 'TCS-123')
ok('staff cannot edit order total', !!(await err(`update orders set subtotal=1 where id=$1`, [o2.id])))
await as(alice)
ok('customer cannot cancel shipped', (await err(`select cancel_order($1)`, [o2.id]))?.code === '22023')
ok('customer cannot change status', (await err(`select update_order_status($1,'delivered')`, [o2.id]))?.code === '42501')
ok('customer cannot record payment', (await err(`select record_payment($1,'paid')`, [o2.id]))?.code === '42501')
await as(shop)
ok('payment recorded', (await q(`select payment_status from orders where id=$1`, [o2.id]))[0].payment_status === 'paid')
ok('payment reference kept', (await q(`select provider_reference from payments where order_id=$1`, [o2.id]))[0].provider_reference === 'BANK-REF-1')
ok('adjust_stock refuses sale reason', (await err(`select adjust_stock($1, -1, 'sale')`, [vars[0].id]))?.code === '22023')
ok('stock cannot go negative', !!(await err(`select adjust_stock($1, -5, 'damaged')`, [vars[0].id])))
await q(`select adjust_stock($1, 2, 'intake', 'New bale')`, [vars[1].id])
ok('adjust_stock intake re-activates', (await q(`select status from products where id=$1`, [pid]))[0].status === 'active')

// pending-order cap
await q(`select adjust_stock($1, 10, 'intake')`, [vars[1].id])
await as(bob)
for (let i = 0; i < 3; i++) await q(`select place_order($1::jsonb,$2::jsonb,$3::jsonb,'cod')`, [items([[vars[1].id, 1]]), contact, addr])
ok('pending-order cap enforced', (await err(`select place_order($1::jsonb,$2::jsonb,$3::jsonb,'cod')`, [items([[vars[1].id, 1]]), contact, addr]))?.code === '22023')

// ── Dashboard module (0006) ─────────────────────────────────────────────────
console.log('\n# Dashboard: settings, costs, sizes, returns, aggregates')
