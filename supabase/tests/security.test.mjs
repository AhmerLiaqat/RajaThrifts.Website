await q(`insert into product_costs (product_id, purchase_price, supplier_ref) values ($1, 12000, 'Bale UK-17')`, [pid])
ok('shopkeeper records purchase price', (await q(`select purchase_price::text p from product_costs where product_id=$1`, [pid]))[0]?.p === '12000.00')
