/**
 * Gives the SEO edge function the PUBLIC Supabase URL + publishable key (the same values
 * already shipped in the website's JavaScript). Runs after "vite build".
 */
import { readFileSync, writeFileSync } from 'node:fs'

const env = {}
for (const file of ['.env.production', '.env']) {
  try {
    for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
      const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/)
      if (m && !(m[1] in env)) env[m[1]] = m[2].replace(/^["']|["']$/g, '')
    }
  } catch {
    // file is optional
  }
}
const get = (k) => process.env[k] || env[k] || ''
const key = get('VITE_SUPABASE_ANON_KEY')
if (key.startsWith('sb_secret_')) throw new Error('Refusing to expose a SECRET Supabase key to the edge function.')

const out = {
  supabaseUrl: get('VITE_SUPABASE_URL').replace(/\/+$/, ''),
  supabaseKey: key,
  bucket: get('VITE_PRODUCT_IMAGES_BUCKET') || 'product-images',
}
writeFileSync(
  'netlify/edge-lib/seo-env.js',
  `// Generated by scripts/write-edge-env.mjs during the build. Public values only.\nexport default ${JSON.stringify(out, null, 2)}\n`,
)
console.log(`[seo] edge env written (${out.supabaseUrl ? 'Supabase configured' : 'no Supabase: product pages use default tags'})`)
